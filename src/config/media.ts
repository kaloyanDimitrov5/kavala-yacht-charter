/**
 * Media manifest. Filenames are configured here only.
 *
 * Drop real files into /public/media/ using these names. At build time
 * `resolveMedia` (src/lib/media.server.ts) checks each file; a missing file
 * renders a flat placeholder with the same aspect ratio and alt text.
 * Alt text lives in the dictionaries. No stock image URLs.
 */
export type ImageSlot = {
  /** Filename inside /public/media/ */
  file: string;
  /** Width / height, used for the frame and the placeholder */
  aspect: { mobile: string; desktop: string };
};

export type VideoSlot = {
  /** Filenames inside /public/media/. Either may be missing. */
  mp4: string;
  webm: string;
};

